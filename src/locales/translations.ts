export function translateLabel(
  lang: Lang,
  label: string,
  href?: string
): string {
  const path = (href || "").split("?")[0] || "";
  const byHref = path ? HREF_TO_KEY[path] : undefined;
  const byLabel = LABEL_TO_KEY[label.trim()];
  const key = byHref || byLabel;
  if (!key) return label;
  return translations[lang][key] || translations.en[key] || label;
}

export function t(lang: Lang, key: TranslationKey): string {
  return translations[lang][key] || translations.en[key] || key;
}
